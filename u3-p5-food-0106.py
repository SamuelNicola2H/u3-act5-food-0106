import pandas as pd
import matplotlib.pyplot as plt
df_food_india = pd.read_csv('indian_food.csv')
print("\n--- DATOS LEIDOS DESDE CSV, Indian Food 0106 ---")
print(df_food_india)
print("\n--- Mostrar Nombre comida + ingredients 0106 ---")
recetas = df_food_india[['name', 'ingredients']]
print(recetas)
print("\n--- Tiempo de cocinado mostrar 10 registros con head 1392 ---")
nombre_y_tiempo = df_food_india[['name', 'cook_time']].head(10)
print(nombre_y_tiempo)
print("\n--- Grafica comida (X) Tiempo de cocinado (Y) ---")
print("\n--- Grafica comida (X) texto a 30 grados ---")
nombre_y_tiempo.plot.bar(x='name',y='cook_time', rot=30)
plt.title('Comida tipica de India Samuel 0106')
plt.xlabel('Nombre Platillo')
plt.ylabel('Tiempo de Cocinado')
plt.show()
print("\n--- Grafica de varias columnas Samuel 0106 ---")
nombre_y_tiempo_prep = df_food_india[['name', 'prep_time', 'cook_time']].head(10)
nombre_y_tiempo_prep.plot.bar(x='name', y=['prep_time', 'cook_time'], rot=30)
plt.title('Grafica de 2 columnas Samuel 0106')
plt.xlabel('Nombre Platillo')
plt.ylabel('Tiempo de Cocinado Prep y Comida')
plt.show()
nombre_y_tiempo_prep.plot.bar(x='name', stacked=True, rot=30)
plt.title('Grafica Apiladas Samuel 0106')
plt.xlabel('Nombre Platillo')
plt.ylabel('Tiempo de Cocinado Prep y Comida')
plt.show()